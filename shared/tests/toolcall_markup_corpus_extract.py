#!/usr/bin/env python3
"""Extract the toolcall-markup specimen corpus from the agent-transcript archive.

PRD ``plans/toolcall-markup-containment-prd.md`` task alpha, boundary row B13.

WHAT THIS ANSWERS
-----------------
``shared.toolcall_markup.repair`` has to be pinned against REAL corrupted calls,
not invented ones. This module walks the orchestrator's archived agent
transcripts, collects every ``tool_use`` parameter matching the PRD's collection
predicate, and emits one JSONL record per specimen carrying the value, the
call's shape, and the outcome ``repair`` produces for it today.

The emitted file — ``shared/tests/fixtures/toolcall_markup_corpus.jsonl`` — is
the DURABLE artefact. Once committed it has no further dependency on the
archive, which is retention-bounded and will rotate the specimens away (PRD
section 11.4). Re-running this module is only needed to take a fresh snapshot.

WHAT THE CORPUS IS AND IS NOT
-----------------------------
The ``expected_outcome`` column is machine-generated BY the implementation it
pins, so the replay proves regression-stability and determinism, NOT
correctness. Correctness is pinned separately and first by the hand-authored
specimen tests in ``test_toolcall_markup.py``, which were written from the PRD's
parsed-input column before this corpus existed. Two checks in the replay are
non-circular by construction and are the load-bearing ones: the D5 structural
invariant, and re-deriving the collection predicate over every stored value.

HOW IT READS THE ARCHIVE
------------------------
Through ``legibility.inventory.iter_json_lines``, THE low-level streaming
transcript reader, rather than a reader rolled here. That buys the documented
line/file split — a corrupt LINE degrades silently, an unreadable FILE raises
``OSError`` and is skipped, counted and logged (:class:`WalkReport`) — with one
answer to "which exceptions mean unreadable", not a second copy of it.

An earlier version gated each line on a cheap ``'tool_use' in line`` substring
check before ``json.loads``. That is incompatible with the canonical reader,
which parses every line, and it was MEASURED not to matter for a tool that runs
once per snapshot: over 40 files / 17.1 MB / 5670 lines, prefilter-only was
0.16s against 0.78s parsing every line (4.9x), and a full run over the live
5703-file archive takes 1m35s wall (32s CPU). Roughly 80 seconds, once. Do not
reintroduce the prefilter to buy them back.

Run it as::

    uv run --project shared python tests/toolcall_markup_corpus_extract.py \\
        --archive-root /home/leo/src/dark-factory/data/orchestrator/agent-transcripts \\
        --out tests/fixtures/toolcall_markup_corpus.jsonl

## Sentinel-literal hazard — DO NOT "helpfully" un-escape these

Every envelope literal here is spelled with the ``\\x3c`` escape for ``<``, per
``fused_memory/utils/toolcall_xml_leak.py`` lines 77-86, and the emitted JSONL
escapes every ``<`` as its ``\\u003c`` JSON escape. That is not decoration: PRD
G6 explicitly anticipates a future agent hand-editing an expectation row, and it
must be able to do so without emitting an envelope literal inside its own
tool-call argument — which is the very defect this corpus documents. ``\\u003c``
is standard JSON, decoded transparently by ``json.loads``.
"""
