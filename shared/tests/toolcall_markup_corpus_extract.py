# CLI.
# ---------------------------------------------------------------------------

_DEFAULT_ARCHIVE = (
    Path(__file__).resolve().parents[2] / 'data' / 'orchestrator' / 'agent-transcripts'
)
_DEFAULT_OUT = Path(__file__).resolve().parent / 'fixtures' / 'toolcall_markup_corpus.jsonl'


def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description='Extract the toolcall-markup specimen corpus from archived transcripts.',
        epilog=(
            'The archive is gitignored and NOT per-worktree, so from inside a task '
            'worktree pass --archive-root pointing at the main checkout. A run that '
            'walks zero files is reported loudly rather than writing an empty corpus.'
        ),
    )
    parser.add_argument('--archive-root', type=Path, default=_DEFAULT_ARCHIVE)
    parser.add_argument('--out', type=Path, default=_DEFAULT_OUT)
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    args = _build_parser().parse_args(argv)

    walked = sum(1 for _ in iter_transcript_files(args.archive_root))
    if walked == 0:
        # LOUD, not silent: a zero-file walk is the failure mode the nested
        # archive layout produces when the walker forgets to recurse, and an
        # empty corpus would otherwise read as a clean snapshot.
        print(
            f'ERROR: no .jsonl.gz found under {args.archive_root} — '
            'nothing written (check --archive-root, and that the walk recurses)',
            file=sys.stderr,
        )
        return 1

    report = WalkReport()
    records = extract(args.archive_root, report)

    for path, detail in report.unreadable:
        print(f'skipped unreadable transcript {path} ({detail})', file=sys.stderr)
    if report.files_read == 0:
        # LOUD, one level in from the zero-files-walked guard above: files WERE
        # found, so that guard passed, and without this one an archive whose
        # every leaf is half-written would overwrite the committed corpus with
        # an empty file and exit 0.
        print(
            f'ERROR: all {report.files_walked} transcript files under '
            f'{args.archive_root} were unreadable — nothing written',
            file=sys.stderr,
        )
        return 1

    write_corpus(records, args.out)
    repaired = sum(1 for r in records if r['expected_outcome'] == OUTCOME_REPAIRED)
    truncated = sum(1 for r in records if r['truncated'])
    print(
        f'walked {report.files_walked} transcript files under {args.archive_root} '
        f'({report.files_read} read, {len(report.unreadable)} unreadable)\n'
        f'wrote {len(records)} specimens to {args.out} '
        f'({repaired} repaired, {len(records) - repaired} unrepairable, '
        f'{truncated} truncated, {args.out.stat().st_size} bytes)',
        file=sys.stderr,
    )
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
