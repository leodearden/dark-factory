class TestTheCommittedFileIsExactlyWhatTheWriterEmits:
    """Byte-identical round-tripping, which is what makes a re-run reviewable.

    A regenerated corpus whose only diff is key order or spacing would bury the
    rows that actually changed.
    """

    def test_reserializing_the_parsed_corpus_reproduces_the_file(
        self, corpus, tmp_path: Path
    ) -> None:
        out = tmp_path / 'roundtrip.jsonl'
        extract.write_corpus(corpus, out)
        assert out.read_bytes() == Path(CORPUS_PATH).read_bytes()

    def test_writing_the_same_records_twice_is_byte_identical(
        self, corpus, tmp_path: Path
    ) -> None:
        first, second = tmp_path / 'a.jsonl', tmp_path / 'b.jsonl'
        extract.write_corpus(corpus, first)
        extract.write_corpus(corpus, second)
        assert first.read_bytes() == second.read_bytes()

    def test_the_committed_file_carries_no_literal_opening_angle_bracket(self) -> None:
        """Every ``\\x3c`` is escaped, so an agent re-emitting a row is safe.

        The markup corpus is written under the same rule and states why: a row
        quoted back into a tool call must not carry an envelope literal.
        """
        assert '\x3c' not in Path(CORPUS_PATH).read_text(encoding='utf-8')

    def test_the_escape_decodes_transparently(self, corpus) -> None:
        line = json.dumps(corpus[0], sort_keys=True, separators=(', ', ': '))
        assert json.loads(line.replace('\x3c', '\\u003c')) == corpus[0]
