"""Drift-guard tests for _RECON_REPORT_TOOL_GUIDANCE (task-2559).

_RECON_REPORT_TOOL_GUIDANCE (reconciliation/prompts/__init__.py) is generated
from live recon_report FastMCP tool signatures via
render_recon_report_tool_guidance() rather than hand-transcribed, because
hand-maintenance drifted twice — most recently, every example omitted the
required `run_id` kwarg, undetected across a full reviewer round.

This module asserts:
- every report-tool call example in the fully ASSEMBLED stage prompts
  (bare inline examples included, not just the generated guidance block)
  shows `run_id` — this is the only way to catch hand-written inline
  examples like stage2.py's cross-project routing snippets or stage3.py's
  verification pseudocode, which render_recon_report_tool_guidance() never
  touches.
- _frozen_recon_report_tool_guidance() — rendered lazily (reviewer robustness
  finding: NOT at module-import time, so a bad snapshot edit cannot become an
  ImportError for every consumer of the `prompts` package) from
  _FROZEN_RECON_REPORT_SIGNATURE_SPECS through the same template and
  render_call() as the live guidance — equals render_recon_report_tool_guidance(),
  and the frozen signature snapshot matches the live tool signatures (name,
  order, required-ness, and tool-set coverage in both directions). See
  TestFallbackIsDerivedFromTheSameRenderer.

A minimal smoke test also confirms render_recon_report_tool_guidance() runs
cleanly and produces non-empty text. For that GENERATED path specifically,
the module deliberately does not re-introspect live signatures or pin
call-shape substrings on its output: those would be tautological, since the
shipped guidance is generated by iterating the exact same live signatures
such a test would re-check, so the assertions could not fail short of import
already having fallen back. TestFallbackIsDerivedFromTheSameRenderer is
different in kind, not degree: it compares two RENDERS FROM DIFFERENT
SIGNATURE SOURCES — the frozen snapshot vs. live introspection — rather than
re-checking generated text against the signatures that generated it, so it
can genuinely fail when the snapshot drifts.

TestReconReportGuidanceFallback's test_fallback_call_examples_all_carry_run_id
run_id scan is now satisfied by construction (the fallback is generated, and
run_id is required in the snapshot for every tool) — it is retained as a
cheap belt-and-braces guard on the original task-2559 bug, not as the
mechanism that now prevents drift; do not mistake it for one.

start_report is harness-called (agents never call it themselves) and is
intentionally excluded — see reconciliation/prompts/__init__.py.
"""
